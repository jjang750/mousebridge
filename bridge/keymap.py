HID_TO_WIN = {h: w for h, w, m, k in _T if w is not None}
HID_TO_MAC = {h: m for h, w, m, k in _T if m is not None}
HID_TO_PYNPUT = {h: k for h, w, m, k in _T if k}
WIN_TO_HID = {}
MAC_TO_HID = {}
PYNPUT_TO_HID = {}
for h, w, m, k in _T:
    if w is not None:
        WIN_TO_HID.setdefault(w, h)
    if m is not None:
        MAC_TO_HID.setdefault(m, h)
    if k:
        PYNPUT_TO_HID.setdefault(k, h)
# 좌/우 구분 없는 VK 가 들어오는 경우 대비
WIN_TO_HID.update({0x10: L_SHIFT, 0x11: L_CTRL, 0x12: L_ALT})
# pynput 의 비구분 이름
PYNPUT_TO_HID.update({"shift": L_SHIFT, "ctrl": L_CTRL, "alt": L_ALT, "cmd": L_GUI,
                      "alt_gr": R_ALT})

# F13~F15 는 Mac keycode 가 print_screen/scroll_lock/pause 와 겹치므로 Mac→HID 는 F 키 우선
MAC_TO_HID.update({0x69: 0x68, 0x6B: 0x69, 0x71: 0x6A})

SWAP_CMD_CTRL = {L_CTRL: L_GUI, L_GUI: L_CTRL, R_CTRL: R_GUI, R_GUI: R_CTRL}

# macOS flagsChanged 처리용: keycode -> CGEventFlags mask
MAC_MOD_MASK = {
    0x37: 1 << 20, 0x36: 1 << 20,   # cmd
    0x38: 1 << 17, 0x3C: 1 << 17,   # shift
    0x3A: 1 << 19, 0x3D: 1 << 19,   # option
    0x3B: 1 << 18, 0x3E: 1 << 18,   # control
    0x39: 1 << 16,                  # caps lock (토글 상태)
    0x3F: 1 << 23,                  # fn
}


def win_to_hid(vk: int, extended: bool) -> int | None:
    if vk == 0x0D and extended:
        return 0x58  # keypad enter
    return WIN_TO_HID.get(vk)


def mac_to_hid(kc: int) -> int | None:
    return MAC_TO_HID.get(kc)
